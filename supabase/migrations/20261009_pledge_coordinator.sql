-- 1. Extend the administrator records
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS is_default_coordinator BOOLEAN DEFAULT false;

-- Add a status column if it doesn't already exist (needed for eligibility checks)
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS status VARCHAR(50) DEFAULT 'Active';

-- Ensure only one default coordinator exists
DROP INDEX IF EXISTS one_default_coordinator;
CREATE UNIQUE INDEX one_default_coordinator ON profiles(is_default_coordinator) WHERE is_default_coordinator = true;

-- 2. Extend the pledge (donations) records
ALTER TABLE donations ADD COLUMN IF NOT EXISTS coordinator_id UUID REFERENCES profiles(id) ON DELETE SET NULL;
ALTER TABLE donations ADD COLUMN IF NOT EXISTS assignment_status VARCHAR(50) DEFAULT 'Pending Assignment';
ALTER TABLE donations ADD COLUMN IF NOT EXISTS assignment_source VARCHAR(50);
ALTER TABLE donations ADD COLUMN IF NOT EXISTS assigned_at TIMESTAMP WITH TIME ZONE;

-- 3. Notifications table
CREATE TABLE IF NOT EXISTS notifications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES profiles(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    type VARCHAR(50),
    is_read BOOLEAN DEFAULT false,
    link_url VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Assignment History / Audit Log
CREATE TABLE IF NOT EXISTS pledge_assignments_audit (
    id SERIAL PRIMARY KEY,
    pledge_id UUID REFERENCES donations(id) ON DELETE CASCADE,
    prev_coordinator_id UUID REFERENCES profiles(id) ON DELETE SET NULL,
    new_coordinator_id UUID REFERENCES profiles(id) ON DELETE SET NULL,
    assigned_by UUID REFERENCES profiles(id) ON DELETE SET NULL,
    reason TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS on new tables
ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE pledge_assignments_audit ENABLE ROW LEVEL SECURITY;

-- 5. Trigger for automatic pledge assignment
CREATE OR REPLACE FUNCTION assign_pledge_on_insert()
RETURNS TRIGGER AS $$
DECLARE
    default_coord_id UUID;
    is_eligible BOOLEAN;
    super_admin_id UUID;
BEGIN
    -- Find the designated default coordinator and check eligibility
    SELECT id, (status = 'Active' AND role IN ('admin', 'Super Admin'))
    INTO default_coord_id, is_eligible
    FROM profiles
    WHERE is_default_coordinator = true
    LIMIT 1;

    IF default_coord_id IS NOT NULL AND is_eligible THEN
        -- Assign to the eligible coordinator
        NEW.coordinator_id := default_coord_id;
        NEW.assignment_status := 'Assigned';
        NEW.assignment_source := 'Automatic';
        NEW.assigned_at := NOW();
        
        -- Create a notification for the coordinator
        -- We do this as an AFTER INSERT trigger step, but since we are in BEFORE INSERT
        -- we can insert into notifications safely within the same transaction.
        -- BUT WAIT: NEW.id might not be generated yet if it's generated by default.
        -- If id is gen_random_uuid(), we must ensure it's generated.
        IF NEW.id IS NULL THEN
            NEW.id := gen_random_uuid();
        END IF;
        
        INSERT INTO notifications (user_id, title, message, type, link_url)
        VALUES (default_coord_id, 'New Pledge Assigned', 'A new pledge has been automatically assigned to you.', 'PledgeAssignment', '/admin/donations');
    ELSE
        -- Leave unassigned
        NEW.assignment_status := 'Pending Assignment';
        NEW.coordinator_id := NULL;
        
        IF NEW.id IS NULL THEN
            NEW.id := gen_random_uuid();
        END IF;

        -- Notify Super Admin
        SELECT id INTO super_admin_id FROM profiles WHERE role = 'Super Admin' LIMIT 1;
        IF super_admin_id IS NULL THEN
            SELECT id INTO super_admin_id FROM profiles WHERE role = 'admin' LIMIT 1;
        END IF;

        IF super_admin_id IS NOT NULL THEN
            INSERT INTO notifications (user_id, title, message, type, link_url)
            VALUES (super_admin_id, 'Pledge Assignment Failed', 'A new pledge could not be assigned because no eligible default coordinator was found.', 'AssignmentFailure', '/admin/donations');
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS pledge_assignment_trigger ON donations;
CREATE TRIGGER pledge_assignment_trigger
BEFORE INSERT ON donations
FOR EACH ROW
EXECUTE FUNCTION assign_pledge_on_insert();
